  String get nostrSecurityBody => text('settings.nostrSecurityBody');
  String connectedAs(String npub) =>
      param('settings.connectedAs', {'npub': npub.substring(0, 12)});
  String backupBody(bool hasIdentity) => text(
    hasIdentity ? 'settings.backupBodyLinked' : 'settings.backupBodyLocal',
  );
  String get voicePreviewText => text('voice.previewText');
  String get aboutTagline => text('about.tagline');
  String get aboutCredits => text('about.credits');

  String get routeLoadError => text('map.routeLoadError');
  String trackDefaultName(DateTime date) => param('track.defaultNameTemplate', {
    'day': date.day.toString().padLeft(2, '0'),
    'month': date.month.toString().padLeft(2, '0'),
  });

  String shareSummary(String distanceKm, String duration, String pace) => param(
    'share.summaryTemplate',
    {'distanceKm': distanceKm, 'duration': duration, 'pace': pace},
  );

  /// Shown in Settings next to the voice section when the selected language
  /// has no Kokoro voice at all — Bit will still speak, but in English.
  String get voiceUnavailableInLanguage => param(
    'settings.voiceUnavailableInLanguage',
    {'language': wildBitLanguageNames[languageCode] ?? languageCode},
  );

  String decimal(num value, {int digits = 1}) {
    final raw = value.toStringAsFixed(digits);
    const commaLocales = {
      'bg',
      'hr',
      'cs',
      'da',
      'de',
      'el',
      'es',
      'et',
      'fi',
      'fr',
      'hu',
      'it',
      'lv',
      'lt',
      'nl',
      'pl',
      'pt',
      'ro',
      'ru',
      'sk',
      'sl',
      'sv',
    };
    return commaLocales.contains(languageCode)
        ? raw.replaceFirst('.', ',')
        : raw;
  }

  static WildBitLocalizations of(BuildContext context) =>
      Localizations.of<WildBitLocalizations>(context, WildBitLocalizations)!;
}

class WildBitLocalizationsDelegate
    extends LocalizationsDelegate<WildBitLocalizations> {
  const WildBitLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) =>
      wildBitLocales.any((item) => item.languageCode == locale.languageCode);
  @override
  Future<WildBitLocalizations> load(Locale locale) async =>
      WildBitLocalizations(locale);
  @override
  bool shouldReload(WildBitLocalizationsDelegate old) => false;
}

extension WildBitLocalizationContext on BuildContext {
  WildBitLocalizations get l10n => WildBitLocalizations.of(this);
}
