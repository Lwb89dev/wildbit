  String text(String key) {
    final code = languageCode;
    return _short[code]?[key] ??
        (code == 'it' ? _it[key] : null) ??
        _en[key] ??
        key;
  }

  /// Substitutes `{name}` placeholders in [key]'s catalog value with [args].
  String param(String key, Map<String, String> args) {
    var value = text(key);
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }

